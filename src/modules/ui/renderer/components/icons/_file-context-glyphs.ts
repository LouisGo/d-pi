/** Known file glyphs; unknown types use the caller's MIME-aware semantic fallback. */
export function fileContextGlyph(
  name: string,
  fallbackPaths: readonly string[],
  fallbackKind = "generic",
): ComposerTagIcon {
  if (fallbackKind === "pdf")
    return {
      name: "pdf",
      paths: Pdf01Icon.flatMap(([, attributes]) =>
        typeof attributes.d === "string" ? [attributes.d] : [],
      ),
    };
  const extension = /\.([a-z0-9]+)$/i.exec(name)?.[1]?.toLowerCase() ?? "";
  const key = Object.hasOwn(extensions, extension)
    ? extensions[extension]
    : undefined;
  return key
    ? { name: key, viewBox: "0 0 16 16", filled: true, paths: glyphs[key] }
    : { paths: fallbackPaths, name: fallbackKind };
}
